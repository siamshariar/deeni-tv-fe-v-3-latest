/**
 * Android: starts the WebView engine (Chromium and its renderer process) while React Native
 * loads. The players are WebViews; on the TV box (CPU capped at 1.2 GHz) the engine took
 * ~3.3 s to start once the React tree asked for the first one, and that stood in front of
 * YouTube's own start (2026-11-04). A hidden WebView loads about:blank at launch and is
 * destroyed 30 s later, when the players' own pages keep the renderer up. Not when the TV's
 * live page already started with the activity (modules/deeni-live-player): that one does it.
 */
const { withDangerousMod, withMainApplication } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const CALL = 'WebViewWarmup.start(this)';

function kotlin(pkg) {
  return `package ${pkg}

import android.content.Context
import android.os.Handler
import android.os.Looper
import android.webkit.WebView
import expo.modules.deenilive.LivePlayerHost

/** Generated by plugins/withWebViewWarmup.js (see there). */
object WebViewWarmup {
  private var view: WebView? = null

  fun start(context: Context) {
    val main = Handler(Looper.getMainLooper())
    main.post {
      if (view != null || LivePlayerHost.hasWebView) return@post
      view = try {
        WebView(context).apply { loadUrl("about:blank") }
      } catch (_: Throwable) {
        null
      }
      main.postDelayed({
        view?.destroy()
        view = null
      }, 30_000)
    }
  }
}
`;
}

module.exports = function withWebViewWarmup(config) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const pkg = cfg.android?.package;
      if (!pkg) throw new Error('withWebViewWarmup: android.package is not set');
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/java', ...pkg.split('.'));
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, 'WebViewWarmup.kt'), kotlin(pkg));
      return cfg;
    },
  ]);
  return withMainApplication(config, (cfg) => {
    const src = cfg.modResults.contents;
    if (src.includes(CALL)) return cfg;
    const next = src.replace(/(\n(\s*)super\.onCreate\(\)\n)/, `$1$2${CALL}\n`);
    if (next === src) throw new Error('withWebViewWarmup: super.onCreate() not found in MainApplication');
    cfg.modResults.contents = next;
    return cfg;
  });
};
